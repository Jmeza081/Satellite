'use strict';

/**
 * Regenerates data/vscode-color-keys.json from the VS Code documentation source.
 *
 * The old lint script scraped the rendered docs page on every run, which meant the
 * build needed network access and broke whenever the page markup changed. This
 * script does the fetch once, on demand, and commits the result so normal builds
 * and CI stay offline and deterministic.
 *
 *   node ./scripts/update-color-keys.js
 */

const fs = require('fs');
const path = require('path');
const https = require('https');

const SOURCE_URL =
    'https://raw.githubusercontent.com/microsoft/vscode-docs/main/api/references/theme-color.md';

const OUT_FILE = path.join(__dirname, '..', 'data', 'vscode-color-keys.json');

// A color key looks like `editorGroupHeader.tabsBackground` - dot-separated
// identifier segments, no spaces, no punctuation beyond the dots.
const KEY_LINE = /^-\s+`([A-Za-z][A-Za-z0-9]*(?:\.[A-Za-z0-9]+)*)`\s*:/;

function get(url) {
    return new Promise((resolve, reject) => {
        https
            .get(url, (res) => {
                if (res.statusCode !== 200) {
                    res.resume();
                    reject(new Error(`${url} responded ${res.statusCode}`));
                    return;
                }
                let body = '';
                res.setEncoding('utf8');
                res.on('data', (chunk) => (body += chunk));
                res.on('end', () => resolve(body));
            })
            .on('error', reject);
    });
}

function extract(markdown) {
    const keys = new Map();
    let section = 'Unsectioned';

    for (const line of markdown.split('\n')) {
        const heading = line.match(/^#{2,3}\s+(.+?)\s*$/);
        if (heading) {
            section = heading[1].replace(/\s*colors?$/i, '').trim();
            continue;
        }

        const match = line.match(KEY_LINE);
        if (!match) continue;

        const key = match[1];
        // Settings and CSS variables also use backticks in this document; real
        // color keys always contain at least one lowercase leading segment and
        // are never single generic words like "json".
        if (!keys.has(key)) keys.set(key, section);
    }

    return keys;
}

(async () => {
    process.stdout.write(`Fetching ${SOURCE_URL}\n`);
    const markdown = await get(SOURCE_URL);
    const keys = extract(markdown);

    if (keys.size < 500) {
        throw new Error(
            `Only extracted ${keys.size} keys - the source format has probably changed. ` +
                'Refusing to overwrite the committed list.',
        );
    }

    const payload = {
        $comment:
            'Generated by scripts/update-color-keys.js - do not edit by hand. ' +
            'Run that script to refresh against the current VS Code docs.',
        source: SOURCE_URL,
        generatedAt: new Date().toISOString().slice(0, 10),
        count: keys.size,
        keys: [...keys.keys()].sort(),
        sections: Object.fromEntries([...keys.entries()].sort()),
    };

    fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
    fs.writeFileSync(OUT_FILE, JSON.stringify(payload, null, 2) + '\n');
    process.stdout.write(
        `Wrote ${keys.size} color keys to ${path.relative(process.cwd(), OUT_FILE)}\n`,
    );
})().catch((err) => {
    process.stderr.write(String(err.stack || err) + '\n');
    process.exit(1);
});
